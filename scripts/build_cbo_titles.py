"""Build src/payroll_sentinel/cbo_titles.py from the official CBO 2002 tables.

The CBO (Classificação Brasileira de Ocupações) is published by the Ministério do
Trabalho e Emprego at cbo.mte.gov.br > Downloads > "Estrutura CBO (CSV)". Unzip it
and pass the folder:

    python scripts/build_cbo_titles.py PATH/TO/CBO_FOLDER

The CBO codes chosen for each family were reviewed and approved by hand (see the
README). Each code contributes its official title and every synonym, cleaned like a
job title. A phrase that would point to two families is dropped.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))
from payroll_sentinel.normalize import clean_title  # noqa: E402

CODES = {
    "software_engineer": ["212205", "212405", "212425", "212430", "317105", "317110", "317120"],
    "data_scientist": ["211220"],
    "hr_analyst": ["252405"],
    "financial_analyst": ["252545", "252510", "252525"],
    "sales_rep": ["354120", "354135", "354140", "354145", "354705", "521105", "521110", "142320"],
    "customer_support": ["422305", "422310", "422315", "422320", "422335", "212420", "142360",
                         "142365"],
    "production_operator": ["784205", "813125", "721215", "721405", "721410", "721415", "721420",
                            "721425", "721430"],
    "maintenance_technician": ["300105", "300305", "313120", "313125", "313205", "313210", "314405",
                               "314410", "911105", "911110", "911115", "911120", "911125", "911130",
                               "911135", "911305", "911310", "911315", "911320", "911325", "919105",
                               "951105", "954125", "910105", "950105", "950110", "950305"],
}
OUT = Path(__file__).resolve().parents[1] / "src" / "payroll_sentinel" / "cbo_titles.py"


def phrases(title: str) -> list[str]:
    """Official wording without its parenthetical qualifier, e.g. '(técnico)'; for titles
    such as 'Analista de sucesso do cliente - customer success', also the part before ' - '."""
    text = re.sub(r"\([^)]*\)", " ", title)
    out = [clean_title(text)]
    if " - " in text:
        out.append(clean_title(text.split(" - ")[0]))
    return [p for p in out if p]


def main() -> None:
    folder = Path(sys.argv[1])
    read = lambda name: pd.read_csv(folder / f"CBO2002 - {name}.csv", sep=";", dtype=str,
                                    encoding="latin-1")
    rows = pd.concat([read("Ocupacao"), read("Sinonimo")])
    family_of = {code: fam for fam, codes in CODES.items() for code in codes}
    missing = sorted(set(family_of) - set(rows["CODIGO"]))
    if missing:
        raise SystemExit(f"Codes not in this CBO edition: {missing}")
    rows = rows[rows["CODIGO"].isin(family_of)].assign(
        phrase=lambda d: d["TITULO"].map(phrases), family=lambda d: d["CODIGO"].map(family_of))
    rows = rows.explode("phrase").dropna(subset=["phrase"])
    families = rows.groupby("phrase")["family"].agg(set)
    ambiguous = sorted(p for p, f in families.items() if len(f) > 1)
    table = {p: next(iter(f)) for p, f in sorted(families.items()) if len(f) == 1}

    lines = [
        '"""Generated by scripts/build_cbo_titles.py from the CBO 2002 tables (Ministério do',
        'Trabalho e Emprego, cbo.mte.gov.br, "Estrutura CBO (CSV)", downloaded 2026-11-15).',
        "Do not edit by hand.",
        "",
        f"{len(table)} official titles and synonyms of {len(family_of)} CBO occupations, cleaned",
        "like job titles (accents, case and parenthetical qualifiers removed), each mapped to",
        f"the family whose CBO codes contain it. Dropped as ambiguous: {len(ambiguous)}.",
        '"""',
        "",
        "CBO_CODES: dict[str, list[str]] = {",
        *[f"    {fam!r}: {codes!r}," for fam, codes in CODES.items()],
        "}",
        "",
        "CBO_TITLES: dict[str, str] = {",
        *[f"    {p!r}: {f!r}," for p, f in table.items()],
        "}",
        "",
    ]
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"{len(table)} phrases for {len(family_of)} codes written to {OUT}; ambiguous: {ambiguous}")
    print(pd.Series(table).value_counts().to_string())


if __name__ == "__main__":
    main()
